import type { GameResult } from '@cotuong/game-core';

export interface PuzzleDef {
  /** Số thế, 1..200 (trùng số "第NNN局" trong nguồn) */
  id: number;
  /** Số thế 3 chữ số, ví dụ "001" */
  code: string;
  /** Tên chữ Hán như trong nguồn (thế 1–100 đã đối chiếu với tài liệu của người dùng) */
  han: string;
  /** Phiên âm Hán Việt theo tài liệu của người dùng — CHƯA được duyệt chính thức; null = chưa có (thế 101–200) */
  viet: string | null;
  /** Ghi chú duyệt của tài liệu (giữ nguyên văn), null nếu không có */
  note: string | null;
  /** Nguồn đánh dấu "*" ở thế này (nguồn không giải thích ý nghĩa dấu "*") */
  star: boolean;
  /** Thế cờ ban đầu (FEN, Đỏ đi trước) */
  fen: string;
  /**
   * CHỈ có khi đã chứng minh: Đỏ ép chiếu hết được trong mateIn nước của Đỏ, với mọi cách đỡ của Đen, mà nước nào
   * của Đỏ cũng là nước chiếu (liên tục chiếu). Bộ giải đã tìm hết các chuỗi chiếu ngắn hơn và không có; chuỗi
   * ngắn hơn có xen nước không chiếu thì không được tìm.
   * Kiểm chứng: (1) đi lại solution bằng game-core → Đỏ chiếu hết đúng ở nước Đỏ thứ mateIn; (2) cây chứng minh
   * được kiểm tra với MỌI nước đỡ hợp lệ của Đen bằng game-core (khoá thế cờ chính xác, không dùng hash).
   */
  mateIn?: number;
  /**
   * Một đường giải chính (đi kèm mateIn): nước ICCS, Đỏ và Đen xen kẽ, bắt đầu và kết thúc bằng nước Đỏ (nước cuối
   * chiếu hết). Nước của Đen là cách đỡ kéo dài nhất theo bộ giải. Độ dài = 2 × mateIn − 1.
   */
  solution?: readonly string[];
}

